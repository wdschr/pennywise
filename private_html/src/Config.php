<?php

declare(strict_types=1);

final class Config
{
    private static ?array $data = null;

    public static function isInstalled(): bool
    {
        return is_file(self::configPath());
    }

    public static function configPath(): string
    {
        return __DIR__ . '/../config.php';
    }

    public static function load(): array
    {
        if (self::$data === null) {
            if (!self::isInstalled()) {
                self::$data = [];
            } else {
                self::$data = require self::configPath();
            }
        }

        return self::$data;
    }

    public static function get(string $key, mixed $default = null): mixed
    {
        $data = self::load();
        $segments = explode('.', $key);
        $value = $data;

        foreach ($segments as $segment) {
            if (!is_array($value) || !array_key_exists($segment, $value)) {
                return $default;
            }
            $value = $value[$segment];
        }

        return $value;
    }

    /**
     * Write a fresh config.php. Used only by the installer.
     */
    public static function write(array $data): void
    {
        $export = var_export($data, true);
        $contents = "<?php\n\n// Generated by the installer on " . date('Y-m-d H:i:s') . "\n// Do not edit by hand unless you know what you are doing.\n\nreturn {$export};\n";

        $path = self::configPath();
        $tmpPath = $path . '.tmp';

        if (file_put_contents($tmpPath, $contents) === false) {
            throw new RuntimeException('Could not write configuration file. Check that private_html is writable.');
        }

        if (!rename($tmpPath, $path)) {
            @unlink($tmpPath);
            throw new RuntimeException('Could not finalise configuration file.');
        }

        @chmod($path, 0640);
        self::$data = null;
    }

    public static function siteUrl(): string
    {
        $configured = trim((string) self::get('site_url', ''));
        if ($configured !== '') {
            return rtrim($configured, '/');
        }

        $scheme = self::requestIsHttps() ? 'https' : 'http';
        $host = $_SERVER['HTTP_HOST'] ?? 'localhost';

        return $scheme . '://' . $host;
    }

    public static function requestIsHttps(): bool
    {
        if (!empty($_SERVER['HTTPS']) && strtolower((string) $_SERVER['HTTPS']) !== 'off') {
            return true;
        }

        // Common shared-hosting reverse proxy header.
        if (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https') {
            return true;
        }

        return false;
    }
}
